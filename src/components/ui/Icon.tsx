export type IconName = keyof typeof icons;
export const ICON_NAMES = Object.keys(icons);

export function Icon({ name, size = 20, className = '' }: { name: IconName | string; size?: number; className?: string }) {
  const Svg = icons[name as IconName] ?? IconList;
  return <Svg size={size} stroke={1.75} className={`shrink-0 ${className}`} aria-hidden />;
}
